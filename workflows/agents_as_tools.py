
from strands import Agent

from agents.model import get_gemini_model
from agents.planner import create_planner_agent
from agents.researcher import create_researcher_agent
from agents.analyst import create_analyst_agent
from agents.fact_checker import create_fact_checker_agent
from agents.report_writer import create_report_writer_agent


def run_as_tools(topic: str, conversation_history=None):

    conversation_history = conversation_history or []

    planner = create_planner_agent()
    researcher = create_researcher_agent()
    analyst = create_analyst_agent()
    checker = create_fact_checker_agent()
    writer = create_report_writer_agent()

    manager = Agent(
        name="ResearchCoordinator",
        model=get_gemini_model(),
        system_prompt="""
You are the lead coordinator of a multi-agent AI research team.

You MUST use all five specialist agents through their available tools.

Follow this exact sequence:

1. Call research_planner and obtain a research plan.
2. Call web_researcher with the original request and complete plan.
3. Call evidence_analyst with the original request and complete findings.
4. Call fact_checker with findings and analysis.
5. Call report_writer with the plan, findings, analysis and review.

IMPORTANT:
- Pass the actual complete output of each specialist to the next.
- Do not invent missing outputs.
- Preserve the original topic during follow-up questions.
- Resolve references using the supplied conversation history.
- If the user explicitly starts a new topic, research that topic instead.
- Do not call the next specialist if a required previous stage failed.
- Return the actual complete Markdown report from report_writer.
- Include source URLs and references.
- Never replace the report with a short completion message.
""",
        tools=[
            planner.as_tool(
                name="research_planner",
                description="Create a structured research plan."
            ),
            researcher.as_tool(
                name="web_researcher",
                description="Research the topic using web search and return detailed findings with source URLs."
            ),
            analyst.as_tool(
                name="evidence_analyst",
                description="Analyze supplied research findings and identify evidence, themes and gaps."
            ),
            checker.as_tool(
                name="fact_checker",
                description="Review supplied findings and analysis for factual support."
            ),
            writer.as_tool(
                name="report_writer",
                description="Write the complete final Markdown report using all supplied inputs."
            ),
        ],
    )

    result = manager(
        f"""
Complete the full multi-agent research process.

PREVIOUS CONVERSATION:
{conversation_history}

CURRENT USER REQUEST:
{topic}

Call all five specialist tools in the required order.
Pass complete outputs between specialists.
Return the complete final report generated by report_writer.
"""
    )

    return result
